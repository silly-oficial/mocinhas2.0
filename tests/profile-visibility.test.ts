import assert from 'node:assert/strict';
import {restoreGalleryVisibility,publicationInput} from '../shared/profile-visibility';
import type {PersonProfile} from '../shared/people';
const legacy={id:'old',published:false,hidden:true,photos:['/uploads/old.jpg'],videos:[{url:'https://www.tiktok.com/@old/video/7421111111111111111',title:''}]} as PersonProfile;
const restored=restoreGalleryVisibility([legacy])[0];
assert.equal(restored.published,true);assert.equal(restored.hidden,false);
assert.equal(legacy.published,false,'restoration must not mutate the previous snapshot');
assert.deepEqual(restored.photos,legacy.photos);assert.equal(restored.videos[0].kind,'social');assert.equal(restored.videos[0].display_mode,'embed');
assert.equal(publicationInput({published:false},restored).published,true,'saving a visible profile publishes it');
assert.equal(publicationInput({hidden:true},restored).published,false);
assert.equal(publicationInput({},legacy).published,false,'partial saves respect explicit hiding');
assert.equal(publicationInput({hidden:false},legacy).published,true);
assert.throws(()=>publicationInput({hidden:'false'},legacy));
console.log('Gallery visibility: legacy restoration, source normalization and explicit hide/reveal passed.');
