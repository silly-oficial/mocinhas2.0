import assert from 'node:assert/strict';
import {restoreAnimalVisibility,publicationInput} from '../shared/profile-visibility.ts';
import type {PersonProfile} from '../shared/people.ts';
const animal={id:'animal',subjectType:'animal',published:false} as PersonProfile;
const human={id:'legacy',published:false,ageBand:'adolescente'} as PersonProfile;
const hidden={...animal,id:'hidden',hidden:true};
const old=[animal,human,hidden];
const restored=restoreAnimalVisibility(old);
assert.equal(restored[0].published,true);
assert.equal(restored[0].hidden,false);
assert.equal(animal.published,false,'migration must not mutate the previous snapshot');
assert.strictEqual(restored[1],human,'legacy people are never republished or relabeled');
assert.strictEqual(restored[2],hidden,'explicit hidden choices survive migration');
assert.strictEqual(restoreAnimalVisibility(restored),restored,'migration runs only once');
assert.equal(publicationInput({subjectType:'animal'}).published,true,'save publishes new animals without a checkbox');
assert.equal(publicationInput({published:false},restored[0]).published,true,'editing does not silently unpublish animals');
assert.equal(publicationInput({hidden:true},restored[0]).published,false);
assert.equal(publicationInput({},hidden).published,false,'partial updates preserve hidden state');
assert.equal(publicationInput({hidden:false},hidden).published,true,'admin can reveal an animal again');
assert.equal(publicationInput({published:false},human).published,false);
assert.throws(()=>publicationInput({hidden:'false'},animal));
console.log('Visibility passed: animal restoration, automatic publication, hide/reveal, restart persistence and legacy protection.');
